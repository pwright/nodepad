import { promises as fs } from "node:fs"
import path from "node:path"

function normalizePluginManifest(raw) {
  if (!raw || typeof raw !== "object") return null
  if (typeof raw.id !== "string" || raw.id.trim() === "") return null
  if (typeof raw.label !== "string" || raw.label.trim() === "") return null
  if (typeof raw.description !== "string") return null

  return {
    id: raw.id,
    label: raw.label,
    description: raw.description,
    enabledByDefault: raw.enabledByDefault === true,
  }
}

async function exists(filePath) {
  try {
    await fs.access(filePath)
    return true
  } catch {
    return false
  }
}

async function loadPlugins(repoRoot) {
  const pluginRoot = path.join(repoRoot, "plugins")

  try {
    const entries = await fs.readdir(pluginRoot, { withFileTypes: true })
    const plugins = []

    for (const entry of entries) {
      if (!entry.isDirectory()) continue

      const manifestPath = path.join(pluginRoot, entry.name, "plugin.json")
      if (!(await exists(manifestPath))) continue

      const raw = JSON.parse(await fs.readFile(manifestPath, "utf8"))
      const manifest = normalizePluginManifest(raw)
      if (!manifest) {
        throw new Error(`Invalid plugin manifest: ${path.relative(repoRoot, manifestPath)}`)
      }

      const hasTsxModule = await exists(path.join(pluginRoot, entry.name, "plugin.tsx"))
      const hasTsModule = await exists(path.join(pluginRoot, entry.name, "plugin.ts"))

      plugins.push({
        dir: entry.name,
        manifest,
        modulePath: hasTsxModule || hasTsModule ? `@/plugins/${entry.name}/plugin` : null,
      })
    }

    plugins.sort((a, b) => a.manifest.label.localeCompare(b.manifest.label))
    return plugins
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
      return []
    }
    throw error
  }
}

function renderRegistrySource(plugins) {
  const imports = [`import type { RegisteredNodepadPlugin } from "@/lib/plugins"`]

  for (const [index, plugin] of plugins.entries()) {
    if (plugin.modulePath) {
      imports.push(`import { plugin as pluginModule${index} } from "${plugin.modulePath}"`)
    }
  }

  const records = plugins.map((plugin, index) => {
    const manifest = JSON.stringify(plugin.manifest, null, 2).replace(/\n/g, "\n    ")
    const moduleLine = plugin.modulePath ? `,\n    module: pluginModule${index}` : ""
    return `  {\n    manifest: ${manifest}${moduleLine}\n  }`
  })

  return `/* eslint-disable */
// Generated by scripts/generate-plugin-registry.mjs. Do not edit manually.

${imports.join("\n")}

export const GENERATED_PLUGINS: RegisteredNodepadPlugin[] = [
${records.join(",\n")}
]
`
}

async function main() {
  const repoRoot = process.cwd()
  const plugins = await loadPlugins(repoRoot)
  const outputPath = path.join(repoRoot, "lib", "generated-plugin-registry.ts")
  const source = renderRegistrySource(plugins)
  await fs.writeFile(outputPath, source, "utf8")
  console.log(`Generated ${path.relative(repoRoot, outputPath)} with ${plugins.length} plugin${plugins.length === 1 ? "" : "s"}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
